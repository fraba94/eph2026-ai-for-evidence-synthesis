#!/usr/bin/env python3
"""Turn the workshop screening CSV into ready-to-paste text batches for a chat assistant.

Usage (from the repository root):
  python3 activity/tools/fetch_abstracts.py        # fills missing abstracts into a local, git-ignored file
  python3 beginners/make_batches.py [RECORDS.csv] [--size 20]

Default input: activity/data/local/screening_records_full.csv (written by fetch_abstracts.py, with
the abstracts the repository cannot ship) if it exists, otherwise the shipped
activity/data/screening_records.csv, in which some abstracts are empty (a warning lists them).

Writes beginners/batches/screening_batch_all.md (every record) and
beginners/batches/screening_batch_NN.md (batches of --size records), each with a
record count at the top so you can check that the assistant returned every row.
Standard library only.
"""
import argparse
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = "activity/data/screening_records.csv"
ROOT = os.path.dirname(HERE)


def block(rows):
    out = [f"RECORDS ({len(rows)} in total: expect exactly {len(rows)} rows back)", ""]
    for r in rows:
        out.append(f"record_id: {r['record_id'].strip()}")
        out.append(f"title: {' '.join((r.get('title') or '').split())}")
        abstract = " ".join((r.get("abstract") or "").split()) or "[no abstract available]"
        out.append(f"abstract: {abstract}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def write(path, title, rows):
    with open(path, "w", encoding="utf-8") as f:
        f.write(f"<!-- {title}. Generated by beginners/make_batches.py from {SOURCE}. Do not publish: abstracts may be copyrighted. -->\n")
        f.write("Copy everything inside the box below and paste it after the screening prompt.\n\n")
        f.write("```text\n" + block(rows) + "```\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("records", nargs="?", default=None)
    ap.add_argument("--size", type=int, default=20)
    a = ap.parse_args()
    if a.records is None:
        full = os.path.join(ROOT, "activity", "data", "local", "screening_records_full.csv")
        a.records = full if os.path.isfile(full) else os.path.join(ROOT, "activity", "data", "screening_records.csv")
    global SOURCE
    SOURCE = os.path.relpath(a.records, ROOT)
    with open(a.records, newline="", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    print(f"Input: {SOURCE}")
    empty = [r["record_id"] for r in rows if not (r.get("abstract") or "").strip()]
    if empty:
        print(f"WARNING: {len(empty)} record(s) have an empty abstract: {', '.join(empty[:15])}{' ...' if len(empty) > 15 else ''}")
        print("         Run `python3 activity/tools/fetch_abstracts.py` first, or use the records page (batch.html).")
    outdir = os.path.join(HERE, "batches")
    os.makedirs(outdir, exist_ok=True)
    write(os.path.join(outdir, "screening_batch_all.md"), f"All {len(rows)} records", rows)
    n = 0
    for i in range(0, len(rows), a.size):
        n += 1
        write(os.path.join(outdir, f"screening_batch_{n:02d}.md"),
              f"Batch {n}: records {i + 1}-{min(i + a.size, len(rows))} of {len(rows)}", rows[i:i + a.size])
    print(f"{len(rows)} records -> {outdir} (1 full file + {n} batches of up to {a.size})")


if __name__ == "__main__":
    main()
